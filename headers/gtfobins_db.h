static inline const GTFOBinPayload* find_gtfobin_payload(const char *bin_name) {
    if (!bin_name) return NULL;
    for (size_t i = 0; gtfobins_db[i].binary_name != NULL; i++) {
        if (strcmp(gtfobins_db[i].binary_name, bin_name) == 0) {
            return &gtfobins_db[i];
        }
    }
    return NULL;
}

